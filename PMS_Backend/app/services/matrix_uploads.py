"""Matrix configuration uploads: validate-only preview, then all-or-nothing confirm.

The workbook is a template generated by the portal (matrix_templates). The
preview parses and validates it completely and writes nothing. Confirm
repeats the same checks and, only if no problem remains, saves the whole
configuration as a DRAFT in the caller's single transaction:
  * no matrix code        -> a new matrix (version 1)
  * code, open draft      -> that draft's content is replaced
  * code, no open version -> a new draft version (a revision)
The uploader, file name, SHA-256, template and schema versions are recorded
on the version and in the audit trail. Workbooks of another layout or schema
version are rejected with an explanation unless the type registers an
explicit, tested conversion.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.auth.permissions import Permission, Principal
from app.models import Department, Matrix, MatrixVersion, MatrixVersionStatus, Plant
from app.services import matrix_rules as rules
from app.services import matrix_service as service
from app.services.audit import AuditActor
from app.services.errors import Issue, NotFoundError, PermissionDeniedError, ValidationFailedError
from app.services.applicability import ApplicabilityInput, applicability_writable
from app.services.matrix_templates import (
    ALL,
    TEMPLATE_KIND,
    TEMPLATE_VERSION,
    Located,
    ParsedWorkbook,
    parse_workbook,
)
from app.services.matrix_types import REGISTRY, MatrixTypeSpec

_SHEETS = {"fields": ("Fields", "field_rows"), "rules": ("Rules", "rule_rows"),
           "test_cases": ("Test cases", "case_rows")}
_PATH = re.compile(r"^(fields|rules|test_cases)\[(\d+)\]")


@dataclass
class UploadPlan:
    parsed: ParsedWorkbook
    spec: MatrixTypeSpec | None = None
    action: str | None = None  # create | update_draft | new_version
    matrix: Matrix | None = None
    target: MatrixVersion | None = None
    code: str | None = None
    name: str | None = None
    description: str | None = None
    attributes: dict[str, Any] = field(default_factory=dict)
    effective_from: date | None = None
    effective_to: date | None = None
    change_summary: str | None = None
    applicability: list[ApplicabilityInput] = field(default_factory=list)
    applicability_labels: list[str] = field(default_factory=list)
    definition: dict[str, Any] = field(default_factory=dict)
    schema_version: int | None = None
    template_version: int | None = None
    problems: list[Located] = field(default_factory=list)
    warnings: list[Located] = field(default_factory=list)
    report: rules.Report | None = None
    parsed_definition: rules.Definition | None = None

    @property
    def ready(self) -> bool:
        return not self.problems and self.report is not None and self.report.ok


def _locate(path: str, parsed: ParsedWorkbook) -> str:
    match = _PATH.match(path)
    if match:
        sheet, rows_attr = _SHEETS[match.group(1)]
        row = getattr(parsed, rows_attr).get(int(match.group(2)))
        return f"{sheet} sheet, row {row}" if row else f"{sheet} sheet"
    if path.startswith("no_match"):
        return "Matrix sheet"
    for key, (sheet, _rows) in _SHEETS.items():
        if path.startswith(key):
            return f"{sheet} sheet"
    return "Workbook"


def _int(value: Any) -> int | None:
    try:
        return int(value) if value is not None and not isinstance(value, bool) else None
    except (TypeError, ValueError):
        return None


def _optional_date(value: Any, label: str, plan: UploadPlan) -> date | None:
    if rules._blank(value):
        return None
    try:
        return rules.parse_date(value)
    except ValueError:
        plan.problems.append(Located("Matrix sheet", f"{label}: enter a date as YYYY-MM-DD."))
        return None


def analyse_upload(db: Session, principal: Principal, data: bytes) -> UploadPlan:
    """Everything the preview shows; writes nothing."""
    if principal.scope_for(Permission.MATRIX_WRITE).is_empty:
        raise PermissionDeniedError("Only HR Head users can upload matrix configurations.")
    parsed = parse_workbook(data)
    plan = UploadPlan(parsed=parsed, problems=list(parsed.problems))
    meta = parsed.meta

    if meta.get("template_kind") != TEMPLATE_KIND:
        plan.problems.append(Located("Workbook", "This is not a matrix configuration template."))
        return plan
    plan.template_version = _int(meta.get("template_version"))
    if plan.template_version != TEMPLATE_VERSION:
        plan.problems.append(Located(
            "Workbook", f"This workbook uses template layout {meta.get('template_version')}, which "
                        f"is no longer supported (current: {TEMPLATE_VERSION}). Download a fresh "
                        "template; your values were not changed."))
        return plan
    spec = REGISTRY.get(str(meta.get("matrix_type") or ""))
    if spec is None:
        plan.problems.append(Located("Workbook", f"Unknown matrix type '{meta.get('matrix_type')}'."))
        return plan
    plan.spec = spec
    settings = parsed.settings
    if str(settings.get("matrix_type") or spec.code).strip() != spec.code:
        plan.problems.append(Located("Matrix sheet", "The matrix type was changed; it must stay "
                                                     f"{spec.code}."))
    plan.schema_version = _int(meta.get("schema_version"))
    definition = parsed.definition
    if plan.schema_version != spec.schema_version:
        try:
            definition = rules.migrate_definition(spec, definition, plan.schema_version or 0)
            plan.warnings.append(Located("Workbook", f"Converted from schema version "
                                                     f"{plan.schema_version} to "
                                                     f"{spec.schema_version}."))
        except rules.SchemaMismatch as exc:
            plan.problems.append(Located(
                "Workbook", f"This workbook was generated for an incompatible version of the "
                            f"{spec.name.lower()} ({exc}) Download the current template."))
            return plan
    plan.definition = definition

    code = settings.get("matrix_code")
    plan.code = None if rules._blank(code) else str(code).strip().upper()
    plan.name = " ".join(str(settings.get("name") or "").split()) or None
    plan.description = str(settings.get("description") or "").strip() or None
    plan.change_summary = str(settings.get("change_summary") or "").strip()[:1000] or None
    if not plan.name:
        plan.problems.append(Located("Matrix sheet", "Give the matrix a name."))
    elif len(plan.name) > 150:
        plan.problems.append(Located("Matrix sheet", "The name is longer than 150 characters."))
    for attribute in spec.attributes:
        value = str(settings.get(f"attr:{attribute.key}") or "").strip().upper()
        if value not in attribute.allowed_values:
            plan.problems.append(Located("Matrix sheet", f"{attribute.label}: choose one of "
                                                         f"{', '.join(attribute.allowed_values)}."))
        plan.attributes[attribute.key] = value
    plan.effective_from = _optional_date(settings.get("effective_from"), "Effective from", plan)
    plan.effective_to = _optional_date(settings.get("effective_to"), "Effective to", plan)
    if plan.effective_from and plan.effective_to and plan.effective_to < plan.effective_from:
        plan.problems.append(Located("Matrix sheet", "Effective to is before effective from."))

    plants = {p.code.upper(): p for p in db.scalars(select(Plant)).all()}
    departments = {d.code.upper(): d for d in db.scalars(select(Department)).all()}
    seen = set()
    for plant_code, dept_code, row in parsed.applicability:
        where = f"Applies to sheet, row {row}"
        plant = None if plant_code in ("", ALL) else plants.get(plant_code)
        department = None if dept_code in ("", ALL) else departments.get(dept_code)
        if plant_code not in ("", ALL) and plant is None:
            plan.problems.append(Located(where, f"Plant code '{plant_code}' not found."))
            continue
        if dept_code not in ("", ALL) and department is None:
            plan.problems.append(Located(where, f"Department code '{dept_code}' not found."))
            continue
        key = (plant.id if plant else None, department.id if department else None)
        if key in seen:
            plan.problems.append(Located(where, "The same plant and department are listed twice."))
            continue
        seen.add(key)
        plan.applicability.append(ApplicabilityInput(*key))
        plan.applicability_labels.append(
            f"{department.name if department else 'All departments'} — "
            f"{plant.name if plant else 'all plants'}")
    if not plan.applicability:
        plan.problems.append(Located("Applies to sheet", "List where the matrix applies (ALL / "
                                                         "ALL for company-wide)."))
    write_scope = principal.scope_for(Permission.MATRIX_WRITE)
    if any(not applicability_writable(write_scope, a) for a in plan.applicability):
        plan.problems.append(Located("Applies to sheet", "You can only configure matrices within "
                                                         "your own scope (company-wide needs "
                                                         "company-wide access)."))

    if plan.code:
        matrix = db.scalars(select(Matrix).where(Matrix.code == plan.code)).one_or_none()
        try:
            matrix = service.get_matrix(db, principal, matrix.id) if matrix else None
        except NotFoundError:  # not visible: the same answer as not found
            matrix = None
        if matrix is None:
            plan.problems.append(Located("Matrix sheet", f"Matrix {plan.code} was not found in "
                                                         "your access. Leave the code empty to "
                                                         "create a new matrix."))
        elif matrix.matrix_type != spec.code:
            plan.problems.append(Located("Matrix sheet", f"Matrix {plan.code} is not a "
                                                         f"{spec.name.lower()}."))
        else:
            plan.matrix = matrix
            open_version = service.open_version(matrix)
            if open_version is not None and open_version.status == MatrixVersionStatus.SUBMITTED:
                plan.problems.append(Located(
                    "Workbook", f"Version {open_version.version_no} of {matrix.code} is awaiting "
                                "CHRO approval. Withdraw it first, or wait for the decision."))
            elif open_version is not None:
                plan.action, plan.target = "update_draft", open_version
            else:
                plan.action = "new_version"
            if not service.can_write(principal, service.latest_version(matrix)):
                plan.problems.append(Located("Workbook", "You can't change this matrix: it "
                                                         "applies beyond your scope."))
            if matrix.attributes != plan.attributes:
                plan.problems.append(Located("Matrix sheet", "Attributes such as the direction "
                                                             "can't change; create a new matrix "
                                                             "instead."))
            if plan.name and plan.name != matrix.name and db.scalar(select(Matrix.id).where(
                    Matrix.matrix_type == spec.code, Matrix.name == plan.name,
                    Matrix.id != matrix.id)):
                plan.problems.append(Located("Matrix sheet", "Another matrix of this type "
                                                             "already has this name."))
    else:
        plan.action = "create"
        if plan.name and db.scalar(select(Matrix.id).where(Matrix.matrix_type == spec.code,
                                                           Matrix.name == plan.name)):
            plan.problems.append(Located("Matrix sheet", f"A {spec.name.lower()} named "
                                                         f"'{plan.name}' already exists. Use its "
                                                         "code to change it."))

    plan.parsed_definition, plan.report = rules.analyse(spec, definition, plan.attributes)
    for problem in plan.report.errors:
        plan.problems.append(Located(_locate(problem.path, parsed), problem.message))
    for warning in plan.report.warnings:
        plan.warnings.append(Located(_locate(warning.path, parsed), warning.message))
    if plan.effective_from is None:
        plan.warnings.append(Located("Matrix sheet", "No effective date yet: it is needed before "
                                                     "submission."))
    return plan


def confirm_upload(db: Session, principal: Principal, actor: AuditActor, data: bytes,
                   file_name: str) -> tuple[Matrix, MatrixVersion]:
    """Re-validate and save, all or nothing (the caller commits once)."""
    plan = analyse_upload(db, principal, data)
    if not plan.ready:
        raise ValidationFailedError([Issue(f"{p.location}: {p.message}") for p in plan.problems]
                                    or [Issue("The workbook could not be validated.")])
    upload = service.UploadSource(file_name=file_name, sha256=plan.parsed.sha256,
                                  template_version=plan.template_version or TEMPLATE_VERSION)
    content = service.DraftContent(definition=plan.definition, effective_from=plan.effective_from,
                                   effective_to=plan.effective_to,
                                   applicability=plan.applicability,
                                   change_summary=plan.change_summary)
    assert plan.spec is not None and plan.name is not None
    if plan.action == "create":
        matrix = service.create_matrix(db, principal, actor, matrix_type=plan.spec.code,
                                       name=plan.name, description=plan.description,
                                       attributes=plan.attributes,
                                       applicability=plan.applicability)
        version = service.latest_version(matrix)
    else:
        matrix = plan.matrix
        assert matrix is not None
        if plan.name != matrix.name or plan.description != matrix.description:
            service.update_matrix(db, principal, actor, matrix.id, name=plan.name,
                                  description=plan.description)
        version = plan.target if plan.action == "update_draft" else service.revise(
            db, principal, actor, matrix)
        matrix = service.get_matrix(db, principal, matrix.id)
        version = next(v for v in matrix.versions if v.id == version.id)
    service.save_draft(db, principal, actor, matrix, version, content, upload=upload)
    return matrix, version
