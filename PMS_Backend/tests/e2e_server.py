"""Backend for browser end-to-end tests, bound to the dedicated e2e database.

Started by Playwright (PMS_Frontend/playwright.config.ts):

    python -m tests.e2e_server

Safety guarantees, checked BEFORE anything is written:
  * E2E_DB_NAME must be set, end with "_e2e_test" and differ from DB_NAME
    (development) and TEST_DB_NAME (backend tests).
  * The live connection must report that database (SELECT DATABASE()).
Only then is the schema migrated and the synthetic demo data seeded
(idempotent), and the API served on its own port.

Runs with a throwaway signing key and PMS_E2E_PASSWORD (generated by
Playwright for each run) as the password of every synthetic account.
"""
import os
import secrets
import sys

from dotenv import load_dotenv

from tests import ENV_FILE


def fail(message: str) -> None:
    print(f"[e2e-server] Refusing to start: {message}", file=sys.stderr)
    sys.exit(2)


def configure_environment() -> tuple[str, str, int]:
    load_dotenv(ENV_FILE)
    e2e_db = os.getenv("E2E_DB_NAME", "")
    if not e2e_db:
        fail("E2E_DB_NAME is not set (add E2E_DB_NAME=pms_e2e_test to PMS_Backend/.env).")
    if not e2e_db.endswith("_e2e_test"):
        fail(f"E2E_DB_NAME '{e2e_db}' must end with '_e2e_test'.")
    if e2e_db in {os.getenv("DB_NAME"), os.getenv("TEST_DB_NAME")}:
        fail("E2E_DB_NAME must differ from DB_NAME and TEST_DB_NAME.")

    password = os.getenv("PMS_E2E_PASSWORD", "")
    if len(password) < 12:
        fail("PMS_E2E_PASSWORD (min. 12 characters) must be provided by the test runner.")
    port = int(os.getenv("PMS_E2E_API_PORT", "8001"))
    if port == 8000:
        fail("the e2e API must not use the development port 8000.")

    # Redirect the whole application BEFORE any app module is imported.
    os.environ["DB_NAME"] = e2e_db
    os.environ["AUTH_SECRET_KEY"] = secrets.token_urlsafe(48)
    os.environ["AUTH_COOKIE_SECURE"] = "false"
    os.environ["CORS_ORIGINS"] = os.getenv("PMS_E2E_FRONTEND_ORIGIN", "http://localhost:5174")
    return e2e_db, password, port


def main() -> None:
    e2e_db, password, port = configure_environment()

    from alembic import command
    from alembic.config import Config
    from sqlalchemy import text
    from sqlalchemy.exc import OperationalError

    from app.db import SessionLocal, engine

    try:
        with engine.connect() as conn:
            connected = conn.execute(text("SELECT DATABASE()")).scalar()
    except OperationalError:
        fail(
            f"cannot connect to database '{e2e_db}'. An administrator must create it and grant "
            "access first (see PMS_Frontend/README.md, 'Browser tests')."
        )
    if connected != e2e_db:
        fail(f"connected to '{connected}', expected '{e2e_db}'.")

    config = Config(str(ENV_FILE.parent / "alembic.ini"))
    config.attributes["configure_logger"] = False
    command.upgrade(config, "head")

    from app.seed.runner import seed

    with SessionLocal() as session, session.begin():
        seed(session, demo_password=password)
    print(f"[e2e-server] Database '{e2e_db}' migrated and seeded; serving on port {port}.")

    import uvicorn

    from app.main import app

    uvicorn.run(app, host="localhost", port=port, log_level="warning")


if __name__ == "__main__":
    main()
