import { CheckReport } from './CheckReport'
import { RuleSummaryTable } from './RuleSummaryTable'

const MAX_BYTES = 1_000_000

/** /matrices/upload */
export function MatrixUploadPage() {
        const user = useCurrentUser()
        const allowed = canWriteMatrices(user)
        const types = useApiQuery(allowed ? 'matrix-types' : null, (signal) =>
                listMatrixTypes(signal),
        )
        if (!allowed) return <AccessDenied />
        if (types.error !== undefined)
                return <ErrorState error={types.error} onRetry={types.reload} />
        if (!types.data) return <LoadingState label="Loading matrix types…" />
        return <Uploader types={types.data} />
}

const ACTION_TEXT: Record<NonNullable<MatrixUploadPreview['action']>, string> = {
        create: 'Creates a new matrix with draft version 1',
        update_draft: 'Replaces the content of the open draft',
        new_version: 'Adds a new draft version',
}

function reportRows(preview: MatrixUploadPreview) {
        return [
                ['Severity', 'Where', 'Message'],
                ...preview.problems.map((p) => ['Problem', p.location, p.message]),
                ...preview.warnings.map((p) => ['Warning', p.location, p.message]),
                ...preview.test_results.map((t) => [
                        t.passed ? 'Test passed' : 'Test failed',
                        `Test case: ${t.label}`,
                        t.error ?? '',
                ]),
        ]
}

function Uploader({ types }: { types: MatrixTypeMeta[] }) {
        const [typeCode, setTypeCode] = useState(types[0]?.code ?? '')
        const [file, setFile] = useState<File | null>(null)
        const [fileError, setFileError] = useState<string | null>(null)
        const [preview, setPreview] = useState<MatrixUploadPreview | null>(null)
        const [confirmed, setConfirmed] = useState<MatrixUploadConfirmed | null>(null)
        const [inputKey, setInputKey] = useState(0)
        const template = useAction()
        const check = useAction()
        const save = useAction()

        function chooseFile(chosen: File | null) {
                setPreview(null)
                setConfirmed(null)
                check.clearError()
                save.clearError()
                setFile(chosen)
                if (chosen === null) setFileError(null)
                else if (!chosen.name.toLowerCase().endsWith('.xlsx'))
                        setFileError('Choose an Excel workbook (.xlsx) generated by the portal.')
                else if (chosen.size > MAX_BYTES) setFileError('The file is larger than 1 MB.')
                else setFileError(null)
        }

        async function handleTemplate() {
                const blob = await template.run(() => downloadTypeTemplate(typeCode))
                if (blob) saveBlob(blob, `${typeCode.toLowerCase()}-template.xlsx`)
        }

        async function handleCheck(event: FormEvent) {
                event.preventDefault()
                if (!file || fileError) {
                        setFileError(fileError ?? 'Choose the workbook to upload.')
                        return
                }
                setPreview(null)
                setConfirmed(null)
                const result = await check.run(() => previewMatrixUpload(file))
                if (result) setPreview(result)
        }

        async function handleConfirm() {
                if (!file) return
                const result = await save.run(() => confirmMatrixUpload(file))
                if (result) {
                        setConfirmed(result)
                        setPreview(null)
                        setFile(null)
                        setInputKey((k) => k + 1)
                }
        }

        return (
                <>
                        <PageHeader
                                title="Upload a matrix from Excel"
                                description="Download a template generated from the matrix type (or a version's own workbook from its page), fill it in, and upload it. The file is checked first and nothing is saved until you confirm; formulas are never run."
                                breadcrumbs={[
                                        { label: 'Matrices', to: '/matrices' },
                                        { label: 'Upload from Excel' },
                                ]}
                        />
                        <div className="space-y-4">
                                <section
                                        aria-labelledby="template-heading"
                                        className={`${cardClasses} space-y-3 p-4`}
                                >
                                        <h2
                                                id="template-heading"
                                                className="text-base font-semibold text-slate-900"
                                        >
                                                1. Get a template
                                        </h2>
                                        <p className="text-sm text-slate-700">
                                                The workbook lists the type’s fields with their data
                                                types, units, limits and allowed values, and carries
                                                the template version so an older file is recognised.
                                                To change an existing matrix, download its version
                                                from the version page instead.
                                        </p>
                                        <div className="flex flex-wrap items-end gap-2">
                                                <div className="w-72">
                                                        <SelectField
                                                                label="Matrix type"
                                                                value={typeCode}
                                                                onChange={(e) =>
                                                                        setTypeCode(e.target.value)
                                                                }
                                                                options={types.map((t) => ({
                                                                        value: t.code,
                                                                        label: t.name,
                                                                }))}
                                                        />
                                                </div>
                                                <Button
                                                        isLoading={template.busy}
                                                        onClick={handleTemplate}
                                                >
                                                        <Download
                                                                aria-hidden="true"
                                                                className="size-4"
                                                        />
                                                        Download blank template
                                                </Button>
                                        </div>
                                        <ActionError
                                                error={template.error}
                                                title="The template could not be downloaded"
                                        />
                                </section>

                                <form
                                        onSubmit={handleCheck}
                                        aria-labelledby="file-heading"
                                        className={`${cardClasses} space-y-3 p-4`}
                                >
                                        <h2
                                                id="file-heading"
                                                className="text-base font-semibold text-slate-900"
                                        >
                                                2. Check the file
                                        </h2>
                                        <div className="space-y-1">
                                                <label
                                                        htmlFor="matrix-file"
                                                        className="block text-sm font-medium text-slate-800"
                                                >
                                                        Excel file (.xlsx, up to 1 MB)
                                                </label>
                                                <input
                                                        key={inputKey}
                                                        id="matrix-file"
                                                        type="file"
                                                        accept=".xlsx,application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
                                                        aria-invalid={fileError ? true : undefined}
                                                        aria-describedby={
                                                                fileError
                                                                        ? 'matrix-file-error'
                                                                        : undefined
                                                        }
                                                        className="block w-full text-sm text-slate-800 file:mr-3 file:rounded-md file:border file:border-slate-300 file:bg-white file:px-3 file:py-2 file:text-sm file:font-medium"
                                                        onChange={(e) =>
                                                                chooseFile(
                                                                        e.target.files?.[0] ?? null,
                                                                )
                                                        }
                                                />
                                                {fileError && (
                                                        <p
                                                                id="matrix-file-error"
                                                                className="text-xs font-medium text-red-700"
                                                        >
                                                                {fileError}
                                                        </p>
                                                )}
                                        </div>
                                        <ActionError
                                                error={check.error}
                                                title="The file could not be checked"
                                        />
                                        <Button
                                                type="submit"
                                                variant="primary"
                                                isLoading={check.busy}
                                        >
                                                <FileSpreadsheet
                                                        aria-hidden="true"
                                                        className="size-4"
                                                />
                                                Check file
                                        </Button>
                                </form>

                                {confirmed && (
                                        <Alert
                                                title="Saved as a draft"
                                                action={
                                                        <Link
                                                                to={`/matrices/${confirmed.matrix_id}/versions/${confirmed.version_id}`}
                                                                className={buttonClasses(
                                                                        'secondary',
                                                                        'sm',
                                                                )}
                                                        >
                                                                Open version {confirmed.version_no}{' '}
                                                                of {confirmed.matrix_code}
                                                        </Link>
                                                }
                                        >
                                                Review it and submit it for CHRO approval from the
                                                version page.
                                        </Alert>
                                )}

                                {preview && <UploadResult preview={preview} />}

                                {preview?.ready && (
                                        <section
                                                aria-labelledby="confirm-heading"
                                                className={`${cardClasses} space-y-3 p-4`}
                                        >
                                                <h2
                                                        id="confirm-heading"
                                                        className="text-base font-semibold text-slate-900"
                                                >
                                                        3. Save
                                                </h2>
                                                <p className="text-sm text-slate-700">
                                                        {preview.action
                                                                ? ACTION_TEXT[preview.action]
                                                                : 'Saves the workbook'}
                                                        {preview.matrix_code &&
                                                                ` (${preview.matrix_code})`}
                                                        . The file is checked again when you save,
                                                        and your name and the file name are recorded
                                                        on the version.
                                                </p>
                                                <ActionError
                                                        error={save.error}
                                                        title="Nothing was saved"
                                                />
                                                <Button
                                                        variant="primary"
                                                        isLoading={save.busy}
                                                        onClick={handleConfirm}
                                                >
                                                        Save as draft
                                                </Button>
                                        </section>
                                )}
                        </div>
                </>
        )
}

function UploadResult({ preview }: { preview: MatrixUploadPreview }) {
        const hasReport =
                preview.problems.length + preview.warnings.length + preview.test_results.length > 0
        return (
                <section aria-labelledby="result-heading" className="space-y-4">
                        <h2 id="result-heading" className="text-lg font-semibold text-slate-900">
                                Validation report
                        </h2>
                        {preview.problems.length > 0 ? (
                                <Alert
                                        tone="danger"
                                        assertive
                                        title={`${plural(preview.problems.length, 'problem')} found`}
                                >
                                        Correct the workbook and check it again. Nothing has been
                                        saved.
                                </Alert>
                        ) : (
                                <Alert title="The workbook is valid">
                                        Review the content below, then save.
                                </Alert>
                        )}
                        {hasReport && (
                                <Button
                                        size="sm"
                                        onClick={() =>
                                                saveBlob(
                                                        csvBlob(reportRows(preview)),
                                                        'matrix-upload-report.csv',
                                                )
                                        }
                                >
                                        <Download aria-hidden="true" className="size-4" />
                                        Download the report (CSV)
                                </Button>
                        )}
                        <dl
                                className={`${cardClasses} grid grid-cols-1 gap-3 p-4 text-sm sm:grid-cols-3`}
                        >
                                <div>
                                        <dt className="font-medium text-slate-700">Matrix</dt>
                                        <dd>
                                                {preview.name ?? '—'}{' '}
                                                {preview.matrix_code && (
                                                        <Badge>{preview.matrix_code}</Badge>
                                                )}
                                        </dd>
                                </div>
                                <div>
                                        <dt className="font-medium text-slate-700">Type</dt>
                                        <dd>{preview.type_name ?? '—'}</dd>
                                </div>
                                <div>
                                        <dt className="font-medium text-slate-700">Action</dt>
                                        <dd>
                                                {preview.action ? ACTION_TEXT[preview.action] : '—'}
                                                {preview.target_version_no !== null &&
                                                        ` (version ${preview.target_version_no})`}
                                        </dd>
                                </div>
                                <div>
                                        <dt className="font-medium text-slate-700">In force</dt>
                                        <dd>
                                                {preview.effective_from
                                                        ? `${formatDate(preview.effective_from)}${preview.effective_to ? ` – ${formatDate(preview.effective_to)}` : ' onwards'}`
                                                        : 'No date set'}
                                        </dd>
                                </div>
                                <div>
                                        <dt className="font-medium text-slate-700">Applies to</dt>
                                        <dd>{preview.applicability.join('; ') || '—'}</dd>
                                </div>
                                <div>
                                        <dt className="font-medium text-slate-700">Template</dt>
                                        <dd>
                                                {preview.template_version !== null
                                                        ? `v${preview.template_version}`
                                                        : '—'}
                                                {preview.schema_version !== null &&
                                                        ` · schema v${preview.schema_version}`}
                                        </dd>
                                </div>
                        </dl>
                        {preview.problems.length > 0 && (
                                <Table caption="Problems in the workbook">
                                        <thead>
                                                <tr>
                                                        <Th>Where</Th>
                                                        <Th>Problem</Th>
                                                </tr>
                                        </thead>
                                        <TBody>
                                                {preview.problems.map((p, index) => (
                                                        <tr key={index}>
                                                                <Td className="whitespace-nowrap">
                                                                        {p.location}
                                                                </Td>
                                                                <Td>{p.message}</Td>
                                                        </tr>
                                                ))}
                                        </TBody>
                                </Table>
                        )}
                        {(preview.warnings.length > 0 || preview.test_results.length > 0) && (
                                <CheckReport
                                        report={{
                                                ok: preview.problems.length === 0,
                                                errors: [],
                                                warnings: preview.warnings.map((w) => ({
                                                        path: '',
                                                        message: `${w.location}: ${w.message}`,
                                                })),
                                                test_results: preview.test_results,
                                                gaps: [],
                                        }}
                                        fields={preview.fields}
                                        headingId="upload-check-heading"
                                        heading="Warnings and test cases"
                                        showStatus={false}
                                />
                        )}
                        {preview.rules.length > 0 && (
                                <RuleSummaryTable rules={preview.rules} fields={preview.fields} />
                        )}
                </section>
        )
}
